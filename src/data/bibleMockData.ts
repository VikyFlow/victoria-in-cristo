function book(id: string, name: string, testament: "old" | "new", order: number, chapterCount: number): BibleBook {
  return {
    id,
    name,
    testament,
    order,
    chapterCount,
    slug: name.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/\s+/g, "-"),
    description: "",
    author: "",
    historicalContext: "",
    mainTheme: "",
    centralMessage: "",
    structure: [],
    keyVerses: [],
    gospelLinks: [],
    timeline: [],
    themes: [],
    keywords: [],
    visualSummary: "",
    readingPlan: [],
  };
}

